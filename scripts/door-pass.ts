import { readFile, writeFile } from 'node:fs/promises';
import { rigCatalogue } from '../src/rig/catalogue.ts';
import { frameDurations } from '../src/rig/timing.ts';
import type { Frame } from '../src/types.ts';

/** The occupied pixel rectangle of a frame in its own canvas, inclusive. */
export interface Bounds { x0: number; y0: number; x1: number; y1: number; width: number; height: number }
export function occupied(frame: Frame): Bounds {
  let x0 = Infinity, y0 = Infinity, x1 = -1, y1 = -1;
  frame.grid.forEach((row, y) => [...row].forEach((code, x) => { if (code !== '.') { x0 = Math.min(x0, x); x1 = Math.max(x1, x); y0 = Math.min(y0, y); y1 = Math.max(y1, y); } }));
  return { x0, y0, x1, y1, width: x1 - x0 + 1, height: y1 - y0 + 1 };
}
export const dosBytes = (width: number, height: number): number => Math.ceil(width * height / 2);

// The far-plane exit as the game draws it: a 20 × 35 stone arch with a separate 14 × 32 glow piece for the lit opening.
export const exitPiece = { width: 20, height: 35, openingWidth: 14, openingHeight: 32, openingOffsetX: 3 } as const;
/** Ben's centre column in the 24-wide lab frame: the shoulders, helmet and torso are symmetric about it. */
export const centreColumn = 11;
/** The exit's centre column; Ben's sprite is placed so that his centre column sits on it. */
export const exitCentre = exitPiece.width / 2 - 1;
/** Sprite left edge in exit coordinates (exit origin = the drawn piece's top-left corner). */
export const spriteLeft = exitCentre - centreColumn;
/** Pixels Ben rises up the screen per frame of the walk-in: whole pixels, never down, 7 in all. */
export const rise = [0, 1, 2, 3, 4, 5, 6, 7] as const;
/** Bottom sprite rows hidden per frame. Zero while he is still in front of the arch, then growing until only the top two rows of his helmet show. */
export const hiddenRows = [0, 0, 3, 7, 12, 18, 25, 31] as const;
/** Ben is 33 rows tall: the crown is lab row 3 and the sole row 35, so the sill can hide up to 33 of his rows. */
export const bodyRows = 33;
/** Rows from the top of the lab frame to the foot line (the bottom edge of row 35), which places the canvas against the floor line. */
export const footLineRows = 36;
/** Assumed height, in pixels, of the exit's front lip; the front-layer pass covers this many rows above the sill. */
export const assumedLipRows = 6;

export async function buildDoorPass(frames: Record<string, Frame>): Promise<unknown> {
  const entry = rigCatalogue.find(item => item.animation === 'door-walk-in')!, rig = entry.rig, durations = frameDurations(rig), total = durations.reduce((a, b) => a + b, 0);
  let start = 0;
  const walkIn = durations.map((durationMs, i) => {
    const name = `${entry.prefix}${i + 1}`, b = occupied(frames[name]), progress = start / total; start += durationMs;
    const left = spriteLeft + b.x0, right = spriteLeft + b.x1;
    return {
      index: i + 1, name, durationMs, progress: Math.round(progress * 1000) / 1000,
      bounds: b,
      // Ben's occupied columns in exit coordinates (inclusive), and how far he spills past the 14-wide lit opening either side.
      exitColumns: { left, right, outsideOpeningLeft: Math.max(0, exitPiece.openingOffsetX - left), outsideOpeningRight: Math.max(0, right - (exitPiece.openingOffsetX + exitPiece.openingWidth - 1)) },
      offsetFromStart: { x: 0, y: -rise[i] },
      overlapsExit: true,
      hiddenRows: hiddenRows[i], visibleRows: bodyRows - hiddenRows[i],
      hiddenByLip: Math.min(hiddenRows[i], assumedLipRows), hiddenByCrop: Math.max(0, hiddenRows[i] - assumedLipRows),
    };
  });
  const saved = JSON.parse(await readFile(new URL('../source/poses.json', import.meta.url), 'utf8')).animations as Record<string, { frames: string[]; durationsMs: number[] }>;
  const sideSet = (animation: string) => {
    const cut = saved[animation], list = cut.frames.map((name, i) => {
      const b = occupied(frames[name]);
      return { index: i + 1, name, durationMs: cut.durationsMs[i], bounds: b };
    });
    return { animation, frames: list.map(({ index, name, durationMs, bounds }) => ({ index, name, durationMs, bounds })), dos: { frameSize: '24x44', bytesPerFrame: dosBytes(24, 44), totalBytes: dosBytes(24, 44) * list.length } };
  };
  const union = (rows: Bounds[]) => ({ width: Math.max(...rows.map(b => b.x1)) - Math.min(...rows.map(b => b.x0)) + 1, height: Math.max(...rows.map(b => b.y1)) - Math.min(...rows.map(b => b.y0)) + 1 });
  const trimmed = union(walkIn.map(f => f.bounds));
  return {
    version: 1,
    note: 'Contract between the lab sprites and the Fizz 2 exit and keyed doors. Pixels are game pixels, x right and y down. Generated by `bun scripts/door-pass.ts`; `scripts/door-pass.test.ts` checks it against the saved frames.',
    farPlaneWalkIn: {
      animation: 'door-walk-in', frames: walkIn.map(f => f.name), canvas: '24x44', view: 'back', loop: false, durationMs: total,
      stunner: 'Ben’s right hip, the viewer’s right (sprite columns 16–19 around rows 23–27); never mirrored',
      exit: { ...exitPiece, origin: 'top-left of the drawn 20 × 35 piece; its bottom edge is the sill baseline', glow: 'separate 14 × 32 piece, assumed centred on the opening column range 3–16 (to be confirmed by the game)' },
      placement: {
        rule: 'spriteX = exitX + spriteLeft; spriteY = (sill baseline + startBelowSill) - 36 (footLineRows) - rise[i]. Ben’s centre column 11 sits on the exit’s centre column 9.',
        spriteLeft, centreColumn, exitCentre, bodyRows, footLineRows,
        startBelowSill: 'game-defined: the floor line minus the sill baseline (the sill is drawn higher on screen than the floor line in front)',
        footLineInSprite: 'the sole’s bottom edge is the bottom of sprite row 35',
      },
      motion: { riseTotalPx: rise[rise.length - 1], rise, sizeStaysTheSame: true },
      layers: {
        drawOrder: 'exit back layer (ground pass), then Ben, then the front-layer pass (lip and lintel).',
        back: 'Everything of the exit that Ben stands in front of: the arch, jambs, the lit glow piece and arrow.',
        front: `The lip: the bottom ${assumedLipRows} rows above the sill baseline across the full 20 px, drawn after Ben so it covers his soles and ankles. The lintel is above Ben’s crown for the whole walk (the arch is 35 tall, Ben is 33 rows tall and rises only 7) and needs no split.`,
        hidingRule: 'Per frame, `hiddenRows` bottom rows of the sprite are not shown. Rows up to `assumedLipRows` come from the front-layer lip; any rows beyond that (hiddenByCrop) are not covered by a 6-row lip, so the game crops them by drawing only the top `visibleRows` rows of the sprite (a source-rectangle crop that rides with Ben), or raises the lip.',
      },
      overlapsExit: 'every frame: Ben’s occupied columns always fall inside the 20 px piece',
      perFrame: walkIn,
      shrink: {
        recommendation: 'Do not scale. Keep Ben at full size and rely on the 7 px rise plus the progressive crop. Nearest-neighbour scaling to about 90 % (33 rows to 30) breaks his one-pixel outline and the lab’s crisp-pixel rule, and a per-frame shrink would need extra art. If the walk still reads as flat, a one-off shrunken last frame would have to be redrawn, not scaled.',
      },
      dos: { frameSize: '24x44', bytesPerFrame: dosBytes(24, 44), totalBytes: dosBytes(24, 44) * walkIn.length, trimmedUnionSize: `${trimmed.width}x${trimmed.height}`, trimmedBytesPerFrame: dosBytes(trimmed.width, trimmed.height), trimmedTotalBytes: dosBytes(trimmed.width, trimmed.height) * walkIn.length },
    },
    sideOnPass: {
      verdict: 'The existing six-frame run serves; no dedicated rig or new art is drawn.',
      reason: 'The keyed doors are 16 × 48 (one tile wide, three tall) against a Ben at most 34 rows tall, so there is nothing to duck under, and a keyed door is passable on the tick the key touches it. The opening animation is presentation only and is drawn before Ben, so Ben is drawn in front of the whole door: there is no front layer to split for keyed doors, and the overlap is a full overlap with the door behind Ben. A run cycle with the Stunner on his right hip (shown facing right, hidden facing left) is what the door needs.',
      door: { width: 16, height: 48, drawOrder: 'ground pass (door, including its opening animation), then Ben', layers: 'one layer, always behind Ben; no front layer' },
      sets: { right: { ...sideSet('walk-run-6') }, left: { ...sideSet('walk-run-left-6') } },
      overlap: {
        horizontal: 'With the door’s left edge at x = 0 and Ben’s sprite at world column u, frame f overlaps the door while u + bounds.x0 < 16 and u + bounds.x1 >= 0, a travel of 16 + bounds.width pixels.',
        vertical: 'Always inside the door: with Ben’s foot line on the door’s bottom edge, his occupied rows are at most 34 of the door’s 48, so 14 or more pixels of door show above his helmet.',
        fullyInsideWidthWhen: 'u + bounds.x0 >= 0 and u + bounds.x1 < 16, which never holds for a frame wider than 16 px (the frames with the arms and legs spread: 17 to 19 wide) and holds for at most a pixel or two for the others.',
      },
      dos: 'The frames are the six-frame run already counted under run-right and run-left: 528 bytes each at 24 × 44, 3,168 per direction, no extra cost.',
    },
  };
}

if (import.meta.main) {
  const { loadSavedFrames } = await import('./motion-metrics.ts');
  const data = await buildDoorPass(loadSavedFrames());
  await writeFile(new URL('../source/ben-door-pass.json', import.meta.url), JSON.stringify(data, null, 2) + '\n');
  console.log('Saved source/ben-door-pass.json.');
}
